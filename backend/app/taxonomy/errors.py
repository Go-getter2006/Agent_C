# 学生端显示用的短名称（不带编码）。没列出的直接用库里的名称。
STUDENT_FACING_NAMES: dict[str, str] = {
    "TY09": "变量没给合适的初值就使用",
    "OT99": "其他错误",
}


def is_error_code(code: str) -> bool:
    return code in ERRORS


def error_name(code: str, student_facing: bool = False) -> str:
    if student_facing and code in STUDENT_FACING_NAMES:
        return STUDENT_FACING_NAMES[code]
    item = ERRORS.get(code)
    return item[0] if item else ""


def error_kp(code: str) -> str:
    item = ERRORS.get(code)
    return item[1] if item else ""
