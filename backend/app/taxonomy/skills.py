def is_skill_code(code: str) -> bool:
    return code in SKILLS


def skill_name(code: str) -> str:
    item = SKILLS.get(code)
    return item[0] if item else ""


def skills_of_kp(kp_code: str) -> list[str]:
    return [c for c in SKILLS if c.startswith(kp_code + ".")]


def skills_for_error(error_code: str) -> list[str]:
    return [c for c, (_n, errs) in SKILLS.items() if error_code in errs]
