# 写进大模型提示里的课程说法。数据结构课的代码也是 C 写的
COURSE_PROMPT = {"C": "C 语言课程", "D": "数据结构课程（代码用 C 语言写）"}


def course_prompt(text: str, course: str) -> str:
    """把提示里的“C 语言课程”换成这门课的说法。"""
    return text.replace("C 语言课程", COURSE_PROMPT.get(course, COURSE_PROMPT["C"]))


def course_of(code: str) -> str:
    """编码属于哪门课：C 或 D。"""
    return "D" if code.startswith("D") else "C"


def kp_of_skill(skill_code: str) -> str:
    """技能所属的知识点：SKILL_KP 里列了的按它，其余看编码前缀（C06.03.02 → C06.03）。"""
    return SKILL_KP.get(skill_code, skill_code[:6])


_RANK = {code: i for i, code in enumerate(KNOWLEDGE_POINTS)}


def kp_rank(kp_code: str) -> int:
    """知识点在教学顺序里排第几（按表的顺序，不按编码；拆出来的新编码排在原来的位置附近）。"""
    return _RANK.get(kp_code, len(_RANK))


def kp_name(kp_code: str) -> str:
    return KNOWLEDGE_POINTS.get(kp_code, "")


def topic_of(kp_code: str) -> str:
    return TOPICS.get(kp_code[:3], "")
