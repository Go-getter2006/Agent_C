def is_cross(edge: tuple[str, str]) -> bool:
    return edge[0][0] != edge[1][0]


def parents_of(include_cross: bool = True) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for a, b in PREREQ_EDGES:
        if include_cross or not is_cross((a, b)):
            out.setdefault(b, []).append(a)
    return out


def children_of(include_cross: bool = True) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for a, b in PREREQ_EDGES:
        if include_cross or not is_cross((a, b)):
            out.setdefault(a, []).append(b)
    return out


def kp_edges() -> list[tuple[str, str, int, bool]]:
    """知识点一层的边：(先修知识点, 后继知识点, 由几条技能边汇总而来, 是不是跨课程)。同一知识点内部的边不算。"""
    counts: dict[tuple[str, str], int] = {}
    for a, b in PREREQ_EDGES:
        ka, kb = a[:6], b[:6]
        if ka != kb:
            counts[(ka, kb)] = counts.get((ka, kb), 0) + 1
    return [(a, b, n, a[0] != b[0]) for (a, b), n in sorted(counts.items())]


def has_cycle() -> bool:
    graph = children_of()
    state: dict[str, int] = {}

    def visit(node: str) -> bool:
        state[node] = 1
        for child in graph.get(node, []):
            if state.get(child) == 1 or (state.get(child) is None and visit(child)):
                return True
        state[node] = 2
        return False

    return any(state.get(n) is None and visit(n) for n in list(graph))


assert not has_cycle(), "先修边成环了"
